#!/usr/bin/env node
/**
 * Generates lib/protected-paths.generated.ts, the list of URLs the middleware gate covers.
 *
 * Why generated: middleware runs on the edge, where it cannot read content-source/ from disk.
 * So the set of protected paths has to be baked into a plain module it can import. This script
 * derives that set from the `access:` tag in the YAML, and runs as part of `npm run build`;
 * validateGraph() in lib/content.ts fails the build if the committed file is stale.
 *
 * A download under public/ is protected only if EVERY piece of content that references it is
 * protected, a file shared with a public page stays public, or that page would break.
 */
const { readFileSync, readdirSync, writeFileSync, statSync } = require("node:fs");
const { join, relative } = require("node:path");
const { parse } = require("yaml");

const ROOT = join(__dirname, "..");
const SRC = join(ROOT, "content-source");
const OUT = join(ROOT, "lib", "protected-paths.generated.ts");
const PUBLIC_DOWNLOADS = join(ROOT, "public", "downloads");

// Only real files count as download references. Prose mentioning e.g.
// "scripts/downloads/generate-lb-guides.js" matches the pattern but is not a URL.
const REAL_DOWNLOADS = new Set(readdirSync(PUBLIC_DOWNLOADS).map((f) => `/downloads/${f}`));

// content-source/<dir> -> the route that renders one of its entries by slug.
const ROUTES = {
  programmes: "/programmes",
  units: "/units",
  materials: "/materials",
  courses: "/courses",
  modules: "/modules",
  glossary: "/glossary",
  "educator-modules": "/educators/training",
};

const NON_PUBLIC = new Set(["staff", "partner"]);

const pages = new Set();
const downloadOwners = new Map(); // "/downloads/x.docx" -> { protected: n, public: n }

function noteDownloads(text, isProtected) {
  for (const [ref] of text.matchAll(/\/downloads\/[A-Za-z0-9._-]+/g)) {
    if (!REAL_DOWNLOADS.has(ref)) continue;
    const owners = downloadOwners.get(ref) ?? { protected: 0, public: 0 };
    owners[isProtected ? "protected" : "public"] += 1;
    downloadOwners.set(ref, owners);
  }
}

for (const dir of readdirSync(SRC)) {
  const dirPath = join(SRC, dir);
  if (!statSync(dirPath).isDirectory()) continue;
  for (const file of readdirSync(dirPath).filter((f) => f.endsWith(".yaml")).sort()) {
    const text = readFileSync(join(dirPath, file), "utf8");
    let doc;
    try {
      doc = parse(text);
    } catch {
      continue; // not our problem here; lib/content.ts reports parse failures
    }
    const entries = Array.isArray(doc) ? doc : [doc];
    const isProtected = entries.some((e) => e && NON_PUBLIC.has(e.access));
    noteDownloads(text, isProtected);
    if (!isProtected) continue;
    const route = ROUTES[dir];
    if (!route) {
      throw new Error(
        `content-source/${dir}/${file} is access: ${entries[0].access}, but ${dir} has no route ` +
          `mapping in scripts/generate-protected-paths.js. The gate would not cover it.`,
      );
    }
    for (const e of entries) {
      if (e && NON_PUBLIC.has(e.access)) pages.add(`${route}/${e.slug}`);
    }
  }
}

const downloads = [...downloadOwners]
  .filter(([, o]) => o.protected > 0 && o.public === 0)
  .map(([ref]) => ref);

const shared = [...downloadOwners]
  .filter(([, o]) => o.protected > 0 && o.public > 0)
  .map(([ref]) => ref);

const body = `// GENERATED by scripts/generate-protected-paths.js. Do not edit by hand.
// Regenerate with: npm run gen:protected-paths (also runs as part of npm run build).
//
// These are the paths middleware.ts puts behind the shared password. Derived from the
// \`access:\` tag on each content file; see lib/access.ts for how it is enforced.

export const PROTECTED_PAGES: readonly string[] = ${JSON.stringify([...pages].sort(), null, 2)};

// Files under public/ referenced only by protected content. Files also referenced by a public
// page are deliberately left open${shared.length ? ` (currently: ${shared.sort().join(", ")})` : ""}.
export const PROTECTED_DOWNLOADS: readonly string[] = ${JSON.stringify(downloads.sort(), null, 2)};
`;

writeFileSync(OUT, body);
console.log(
  `protected paths: ${pages.size} pages, ${downloads.length} downloads` +
    (shared.length ? `, ${shared.length} shared download(s) left public` : ""),
);
